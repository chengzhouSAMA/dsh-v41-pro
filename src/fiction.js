export function apply(ctx, rawConfig = {}) {
  const logger = makeLogger(ctx, name)
  if (rawConfig?.enabled === false) return
  if (typeof ctx?.skills?.register !== 'function') {
    logger.warn('当前组合没有 ctx.skills.register；文学写作 Skill 未注册')
    return
  }
  ctx.effect(() => ctx.skills.register(FICTION_SKILL), name)
}
